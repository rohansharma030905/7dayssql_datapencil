-- 3.Identifies which sales channels generate the highest revenue and helps optimize channel performance.
-- 4.Identifies products generating the highest estimated profit and supports product-level profitability analysis.
-- 5.Identifies the five most popular product categories by sales volume and helps improve inventory allocation.
