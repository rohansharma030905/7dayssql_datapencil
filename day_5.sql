use sql7challenge;

-- Q1. Total Sales Value
-- Calculate total sales value from non-cancelled orders.

SELECT SUM(oi.quantity * oi.unit_price) AS total_sales_value
FROM orders AS o
JOIN order_items AS oi
ON o.order_id = oi.order_id
WHERE o.status <> 'Cancelled';

-- Q2. Sales by Product Category
-- Identify which product categories generate the most sales.

SELECT p.category, SUM(oi.quantity * oi.unit_price) AS total_sales_value
FROM orders AS o
JOIN order_items AS oi
ON o.order_id = oi.order_id
Join products AS p 
ON p.product_id = oi.product_id
WHERE o.status <> 'Cancelled'
GROUP BY p.category
ORDER BY total_sales_value desc
limit 3;

-- Q3. Top 10 Products by Sales Value
-- Find the 10 products generating the highest sales value.

SELECT p.product_id, p.product_name, SUM(oi.quantity * oi.unit_price) AS total_sales
FROM products AS p
JOIN order_items AS oi
ON p.product_id = oi.product_id
JOIN orders AS o
ON oi.order_id = o.order_id
WHERE o.status <> 'Cancelled'
GROUP BY p.product_id, p.product_name
ORDER BY total_sales DESC
LIMIT 10;

-- Q4. Total Quantity Sold by Product
-- Calculate the total quantity sold for each product.
SELECT p.product_id, p.product_name, SUM(oi.quantity) AS total_quantity_sold
FROM products AS p
JOIN order_items AS oi
ON p.product_id = oi.product_id
JOIN orders AS o
ON oi.order_id = o.order_id
WHERE o.status <> 'Cancelled'
GROUP BY p.product_id, p.product_name
ORDER BY total_quantity_sold DESC;

-- Q5. Average Selling Price by Category
-- Calculate the average product selling price in each category.

SELECT p.category, AVG(oi.unit_price) AS average_selling_price
FROM products AS p
JOIN order_items AS oi
ON p.product_id = oi.product_id
JOIN orders AS o
ON oi.order_id = o.order_id
WHERE o.status <> 'Cancelled'
GROUP BY p.category
ORDER BY average_selling_price DESC;

-- Q6. Sales by Sales Channel
-- Calculate sales value generated by each sales channel.

SELECT o.channel, SUM(oi.quantity * oi.unit_price) AS total_sales
FROM orders AS o
JOIN order_items AS oi
ON o.order_id = oi.order_id
WHERE o.status <> 'Cancelled'
GROUP BY o.channel
ORDER BY total_sales DESC;

-- Q7. Estimated Product Profit
-- Task: Calculate estimated profit by product using product cost and item selling price.

SELECT p.product_id, p.product_name,
SUM(oi.quantity * oi.unit_price) AS total_sales,
SUM(oi.quantity * p.cost) AS total_cost,
SUM(oi.quantity * (oi.unit_price - p.cost)) AS estimated_profit
FROM products AS p
JOIN order_items AS oi
ON p.product_id = oi.product_id
JOIN orders AS o
ON oi.order_id = o.order_id
WHERE o.status <> 'Cancelled'
GROUP BY p.product_id, p.product_name
ORDER BY estimated_profit DESC;

-- Q8. Top 5 Categories by Quantity Sold
-- Task: Find the five categories with the highest total quantity sold.

SELECT p.category, SUM(oi.quantity) AS total_quantity_sold
FROM orders AS o
JOIN order_items AS oi
ON o.order_id = oi.order_id
JOIN products AS p
ON oi.product_id = p.product_id
WHERE o.status <> 'Cancelled'
GROUP BY p.category
ORDER BY total_quantity_sold DESC
limit 5;

